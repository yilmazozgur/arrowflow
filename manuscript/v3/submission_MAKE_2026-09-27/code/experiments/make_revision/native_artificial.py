def load(name, protocol, *, loaders=None):
    """(X, y, manifest) of one dataset through the pinned artificial loader, with the completion audit in the manifest."""
    entry = panel_by_name(protocol).get(name)
    if entry is None:
        raise DatasetIdentityError(f'{name} is not in the {FAMILY} panel')
    X, y, manifest = ed.load_artificial_pinned(name, entry, loader=(loaders or {}).get(FAMILY))
    manifest = {**manifest, 'native_input': {'rule': COMPLETION_RULE, 'audit': check_completion(name, X)}}
    return X, y, _plain(manifest)


def check_encoded_run(path=None, *, verify=True):
    """load_run (and by default verify_run) of the encoded comparison arm against the pins recorded here."""
    from .compare_runs import RunComparisonError, load_run, verify_run
    source = Path(path or ENCODED_RUN['path'])
    run = load_run(source, 'encoded')
    observed = {'protocol_id': run.protocol.get('protocol_id'), 'protocol_sha256': run.protocol_sha256,
                'code_revision': run.environment.get('code_revision'), 'summary_sha256': run.summary_sha256,
                'registry': run.environment.get('registry')}
    wrong = [f'{key} pinned {ENCODED_RUN[key]!r}, found {value!r}' for key, value in observed.items()
             if ENCODED_RUN[key] != value]
    if wrong:
        raise RunComparisonError(f'The encoded comparison run at {source} is not the pinned run: ' + '; '.join(wrong))
    if sorted(run.protocol['datasets']) != sorted(ENCODED_RUN['datasets']):
        raise RunComparisonError(f'The encoded run holds {run.protocol["datasets"]}, not the three artificial datasets')
    for name, pins in ENCODED_RUN['datasets'].items():
        found = {key: run.manifests[name].get(key) for key in pins}
        if found != pins:
            raise RunComparisonError(f'The encoded run {name} dataset or splits hash differs from the pins '
                                     f'({found} against {pins}): the folds are not identical')
    missing = [model for model in (*REUSED_COMPARATORS, MAJORITY_MODEL, ENCODED_RUN['arrowflow_model'])
               if model not in run.registry]
    if missing:
        raise RunComparisonError(f'The encoded run does not hold {", ".join(missing)}')
    return run, (verify_run(run)[0] if verify else None)


def prepare(output, protocol, names=None, *, loaders=None, encoded=None, verify_encoded=False):
    """run_revision.prepare for the pinned datasets: the same records and layout, each dataset loaded through its pinned
    loader, its completion audited, and its dataset and splits hashes checked against the panel AND against the encoded run."""
    from .run_revision import environment_record, get_registry, write_json
    validate_native_protocol(protocol)
    if protocol.get('purpose') is not None:
        raise ValueError('prepare serves production protocols; the smoke writes its own synthetic datasets')
    output = Path(output)
    names = list(protocol['datasets'] if names is None else names)
    outside = [name for name in names if name not in protocol['datasets']]
    if outside:
        raise ValueError(f'Datasets outside the protocol datasets: {outside}')
    registry = get_registry(protocol['registry'], protocol)
    write_json(output/'protocol.json', protocol)
    write_json(output/'candidates.json', candidate_record(registry))
    write_json(output/'environment.json', environment_record(protocol['registry']))
    entries = panel_by_name(protocol)
    for name in names:
        X, y, manifest = load(name, protocol, loaders=loaders)
        splits = make_splits(y, protocol['outer_folds'], protocol['outer_repeats'], protocol['inner_folds'],
                             protocol['split_seed'])
        manifest['splits_hash'] = config_id(splits)
        pins = (entries[name].get('dataset_hash'), entries[name].get('splits_hash'))
        if (manifest['dataset_hash'], manifest['splits_hash']) != pins:
            raise DatasetIdentityError(f'{name}: the dataset or splits hash differs from the panel pins')
        encoded_pins = ENCODED_RUN['datasets'][name]
        if (manifest['dataset_hash'], manifest['splits_hash']) != (encoded_pins['dataset_hash'], encoded_pins['splits_hash']):
            raise DatasetIdentityError(f'{name}: the dataset or splits hash differs from the encoded comparison run; the two '
                                       'arms must run on identical folds')
        write_json(output/name/'manifest.json', manifest)
        write_json(output/name/'splits.json', splits)
        destination = output/name/'data.npz'
        if not destination.exists():
            np.savez_compressed(destination, X=X, y=y)
    if encoded is not None or verify_encoded:
        check_encoded_run(encoded, verify=verify_encoded)
    return registry


def run(protocol_path, output, workers):
    """run_revision's run stage for the frozen protocol, with the same checks in the same order."""
    from .reporting import collect_verified_results
    from .run_revision import _worker, environment_record, execution_lock, get_registry, load_prepared, planned_jobs, write_json
    output = Path(output)
    protocol = json.loads(Path(protocol_path).read_text())
    if not protocol.get('frozen'):
        raise ValueError('Confirmatory run requires a reviewed frozen protocol')
    if protocol.get('purpose') is not None:
        raise ValueError('A production run needs the frozen production protocol, not a synthetic smoke protocol')
    validate_native_protocol(protocol)
    saved = json.loads((output/'protocol.json').read_text())
    if saved != protocol:
        raise ValueError('Prepared and frozen protocols differ; prepare a new output directory')
    registry_path = protocol['registry']
    registry = get_registry(registry_path, protocol)
    if canonical_json(json.loads((output/'candidates.json').read_text())) != canonical_json(candidate_record(registry)):
        raise ValueError('Candidate registry changed after prepare')
    if json.loads((output/'environment.json').read_text()) != environment_record(registry_path):
        raise ValueError('Code revision, source, environment, or registry changed after prepare')
    if not 1 <= workers <= MAX_WORKERS:
        raise ValueError(f'Worker count must be between 1 and {MAX_WORKERS}')
    names, entries = list(protocol['datasets']), panel_by_name(protocol)
    for name in names:
        manifest = load_prepared(output, name)[2]
        if (manifest['dataset_hash'], manifest['splits_hash']) != (entries[name]['dataset_hash'], entries[name]['splits_hash']):
            raise DatasetIdentityError(f'{name}: the prepared dataset or splits hash differs from the panel pins')
    write_json(output/'planned_jobs.json', planned_jobs(names, protocol, registry))
    jobs = [(str(output), name, index, model, registry_path) for name in names
            for index in range(protocol['outer_folds'] * protocol['outer_repeats']) for model in registry]
    with execution_lock(), ProcessPoolExecutor(max_workers=workers, mp_context=multiprocessing.get_context('spawn')) as pool:
        for path in pool.map(_worker, jobs):
            print(path, flush=True)
    collect_verified_results(output, names, protocol, registry)


