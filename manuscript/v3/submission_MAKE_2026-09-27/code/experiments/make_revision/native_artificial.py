def observed_sequences(X):
    """Each row's observed sequence as one-based item IDs: the present items ordered by relative position."""
    from .artificial_ranks import sequences_from_features
    return sequences_from_features(X)


def native_orders(X):
    """(n, V) int64: each row completed to a full permutation of the V items, as zero-based item IDs.

    Row i is the present items in ascending relative position, then the items row i omits in ascending item order. The
    matrix is exactly what ArrowFlowEstimator.fit_orders and StableFootruleKNN(input_kind='orders') consume; item k of the
    vocabulary is column k - 1 of X and the network item name str(k).
    """
    values = np.asarray(X, dtype=np.float64)
    if values.ndim != 2 or values.shape[1] < 2:
        raise ValueError('The native input needs a matrix of at least two item columns')
    if np.isinf(values).any():
        raise ValueError('Item positions must be finite or NaN')
    present_counts = np.sum(~np.isnan(values), axis=1)
    if (present_counts < 2).any():
        raise ValueError('Every row needs at least two present items')
    orders = np.empty(values.shape, dtype=np.int64)
    for row, rowvalues in enumerate(values):
        present = np.flatnonzero(~np.isnan(rowvalues))
        head = present[np.argsort(rowvalues[present], kind='stable')]
        tail = np.flatnonzero(np.isnan(rowvalues))          # flatnonzero is ascending: ascending item order
        orders[row] = np.concatenate([head, tail])
    return orders


def missing_counts(X):
    """Number of deleted items per row."""
    return np.sum(np.isnan(np.asarray(X, dtype=np.float64)), axis=1).astype(np.int64)


def missing_items(X):
    """Per row, the tuple of one-based item IDs the row omits, ascending (exactly the appended tail)."""
    values = np.asarray(X, dtype=np.float64)
    return [tuple(int(item) + 1 for item in np.flatnonzero(np.isnan(row))) for row in values]


def filled_positions(X):
    """(n, V) float: each item's zero-based position in the COMPLETED ranking divided by V - 1.

    The same units as artificial_ranks' feature rule (position / (m - 1), m present items), so a row with no deletion has
    exactly its original features and a row with deletions has the completed position where the original has NaN.
    """
    orders = native_orders(X)
    positions = np.empty(orders.shape, dtype=np.float64)
    np.put_along_axis(positions, orders, np.broadcast_to(np.arange(orders.shape[1], dtype=np.float64), orders.shape), axis=1)
    return positions / (orders.shape[1] - 1)


def completion_audit(X):
    """Proof that the completion is a permutation and is reversible; every field must hold before the data are used."""
    values = np.asarray(X, dtype=np.float64)
    orders, sequences, tails = native_orders(values), observed_sequences(values), missing_items(values)
    counts = missing_counts(values)
    vocabulary = np.arange(orders.shape[1])
    permutation = bool(np.all(np.sort(orders, axis=1) == vocabulary))
    reversible = all(tuple(int(item) + 1 for item in orders[row][:len(sequences[row])]) == sequences[row]
                     for row in range(len(orders)))
    tail_matches = all(tuple(int(item) + 1 for item in orders[row][len(sequences[row]):]) == tails[row]
                       for row in range(len(orders)))
    ascending = all(list(tail) == sorted(tail) for tail in tails)
    return {'rows': int(len(orders)), 'vocabulary_size': int(orders.shape[1]),
            'every_row_is_a_permutation_of_the_V_items': permutation,
            'dropping_the_tail_recovers_the_observed_sequence': reversible,
            'the_tail_is_exactly_the_missing_items': tail_matches, 'the_tail_is_in_ascending_item_order': ascending,
            'rows_with_deletions': int((counts > 0).sum()),
            'observed_length_counts': {str(int(length)): int(count)
                                       for length, count in zip(*np.unique(orders.shape[1] - counts, return_counts=True))},
            'distinct_completed_rows': int(len({tuple(row.tolist()) for row in orders})),
            'distinct_observed_sequences': int(len(set(sequences))),
            'collisions_created_by_the_completion': int(len(set(sequences)) - len({tuple(row.tolist()) for row in orders})),
            'rule': COMPLETION_RULE}


def check_completion(name, X):
    """Refuse a dataset whose completion is not a reversible permutation; returns the audit."""
    audit = completion_audit(X)
    failed = [key for key in ('every_row_is_a_permutation_of_the_V_items', 'dropping_the_tail_recovers_the_observed_sequence',
                              'the_tail_is_exactly_the_missing_items', 'the_tail_is_in_ascending_item_order') if not audit[key]]
    if failed:
        raise DatasetIdentityError(f'{name}: the native completion is not reversible ({", ".join(failed)})')
    return audit


