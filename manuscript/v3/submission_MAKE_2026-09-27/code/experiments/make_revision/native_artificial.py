    reported = commands.add_parser('reporting', help='reporting.summarize_verified_results of a completed run')
    reported.add_argument('--output', type=Path, required=True)
    args = parser.parse_args(argv)
    if args.command == 'draft':
        write_json(args.output, draft_protocol())
    elif args.command == 'prepare':
        prepare(args.output, json.loads(args.protocol.read_text()), encoded=args.reference,
                verify_encoded=args.reference is not None)
        print(f'prepared {args.output}')
    elif args.command == 'reference':
        encoded, rows = check_encoded_run(args.reference)
        print(f"encoded run verified: {encoded.provenance()['protocol_id']} at {encoded.environment['code_revision']}, "
              f"{len(encoded.jobs)} jobs, {sum(map(len, rows.values()))} model rows")
    elif args.command == 'data_properties':
        record = data_properties(json.loads(args.protocol.read_text()))
        write_json(args.output, record)
        for name, entry in record['datasets'].items():
            probes = entry['probes']
            print(f"{name}: majority {probes['majority_class']['mean_accuracy']:.4f}; missing-count "
                  f"{probes['missing_count']['mean_accuracy']:.4f} ({probes['missing_count']['above_majority_points']:+.2f} pp); "
                  f"missing-items {probes['missing_items']['mean_accuracy']:.4f} "
                  f"({probes['missing_items']['above_majority_points']:+.2f} pp); collisions "
                  f"{entry['completion_audit']['collisions_created_by_the_completion']}")
    elif args.command == 'smoke':
        if not 1 <= args.workers <= MAX_WORKERS:
            raise ValueError(f'Worker count must be between 1 and {MAX_WORKERS}')
        record = smoke(args.output, args.workers)
        for row in record['primary_family'] + record['secondary_family']:
            print(f"{row['family']} {row['dataset']}: {row['model_a']} - {row['model_b']} {row['mean_difference']:+.4f} "
                  f"Holm p={row['holm_p_approximate']:.3g} (synthetic)")
    elif args.command == 'pilot':
        report = runtime_pilot(args.output, json.loads(args.protocol.read_text()))
        print(json.dumps(report['workload_estimates'], indent=2))
    elif args.command == 'project':
        record = projection(json.loads(args.protocol.read_text()), args.pilot)
        write_json(args.output, record)
        for name, entry in record['per_dataset'].items():
            print(f"{name}: central {entry['central_serial_hours']:.2f} serial h, upper {entry['upper_serial_hours']:.2f}; "
                  f"native ArrowFlow job {entry['arrowflow_job_minutes']['central']:.1f} min")
        print(f"run makespan {record['run']['central']['simulated_makespan_hours']:.2f} h (upper "
              f"{record['run']['upper']['simulated_makespan_hours']:.2f}); decision {record['decision_hours']:.2f} h (upper "
              f"{record['upper_hours']:.2f}) at {record['workers']} workers; within the {record['cap_hours']} h cap: "
              f"{record['within_cap']}")
    elif args.command == 'freeze':
        protocol = freeze(args.draft, args.projection, args.stages, args.output)
        print(f"frozen {protocol['protocol_id']} at {protocol['frozen_at_utc']}: decision "
              f"{protocol['projection']['decision_hours']:.2f} h")
    elif args.command == 'reporting':
        from .reporting import summarize_verified_results
        write_json(args.output/'summary.json', summarize_verified_results(args.output))
        print(f'summary written for {args.output}')
    else:
        protocol = json.loads(args.protocol.read_text())
        workers = args.workers if args.workers is not None else protocol.get('workers', 1)
        run(args.protocol, args.output, workers)


