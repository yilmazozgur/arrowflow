def runtime_pilot(output, protocol, names=None, *, loaders=None):
    """run_revision.runtime_pilot for the pinned datasets: three evenly spaced candidates of every model on the first outer
    training partition, predictions on training rows only; the same rows and estimates; no held-out score."""
    from .evaluation import _fit_predict
    from .run_revision import execution_lock, load_prepared, write_json
    output = Path(output)
    names = list(protocol['datasets'] if names is None else names)
    with execution_lock():
        registry = prepare(output, protocol, names, loaders=loaders)
        rows, identity = [], {}
        for name in names:
            X, y, manifest, splits = load_prepared(output, name)
            identity[name] = {'dataset_hash': manifest['dataset_hash'], 'splits_hash': manifest['splits_hash']}
            train = splits[0]['train']                   # never pass any outer-test sample or label
            for model, spec in registry.items():
                for index in sorted({0, len(spec.candidates) // 2, len(spec.candidates) - 1}):
                    config = spec.candidates[index]
                    start = time.perf_counter()
                    row = {'dataset_id': name, 'model_id': model, 'config': config, 'config_id': config_id(config),
                           'fit_rows': train, 'model_seed': protocol['fit_seeds'][0]}
                    try:
                        _, timing = _fit_predict(spec, config, protocol['fit_seeds'][0], X[train], y[train], X[train])
                        row.update(timing, status='ok', elapsed_seconds=time.perf_counter() - start)
                    except Exception as exc:
                        row.update(status='failed', exception=f'{type(exc).__name__}: {exc}',
                                   elapsed_seconds=time.perf_counter() - start)
                    rows.append(row)
    estimates = {}
    for model, spec in registry.items():
        durations = [row['elapsed_seconds'] for row in rows if row['model_id'] == model and row['status'] == 'ok']
        per_outer = nd.fits_per_outer(len(spec.candidates), spec.stochastic, protocol['inner_folds'])
        total = per_outer * protocol['outer_folds'] * protocol['outer_repeats'] * len(protocol['datasets'])
        estimates[model] = {'fits_per_outer': per_outer, 'panel_fit_count': total,
                            'observed_seconds_min': min(durations) if durations else None,
                            'observed_seconds_max': max(durations) if durations else None,
                            'serial_panel_seconds_using_observed_max': total * max(durations) if durations else None}
    report = {'purpose': 'training_only_runtime_no_heldout_scores', 'family': FAMILY, 'rows': rows,
              'workload_estimates': estimates,
              'estimate_limitations': 'Sampled configurations/datasets; max extrapolation is not a runtime bound; RSS is '
                                      'process lifetime high-water mark.',
              'candidate_reduction': False, 'datasets_piloted': names, 'dataset_identity': identity,
              'protocol_id': protocol['protocol_id'], 'protocol_hash': config_id(protocol)}
    write_json(output/'pilot.json', report)
    return report


# The realized runs whose fit logs calibrate a pilot fit into a production job second, and the model of each whose job
# structure matches one of ours. native_* models have no realized run of their own, so each takes the factor of the
# encoded-run model with the same job structure (same views, same readout selection, same candidate machinery).
CALIBRATION = dict(nd.CALIBRATION)
CALIBRATION_SOURCE = {TRAINED_MODEL: 'arrowflow_full_knn', UNTRAINED_MODEL: 'arrowflow_knn_untrained',
                      INPUT_MODEL: 'input_footrule_knn', FILLED_MODEL: 'numeric_knn'}
CALIBRATION_MODELS = {'bridge_knn': ('arrowflow_full_knn', 'numeric_knn'),
                      'knn_training': ('arrowflow_knn_untrained', 'input_footrule_knn')}
KINDS = {'central': 'pooled', 'upper': 'max'}


def projection(protocol, pilot_path, calibration=None):
    """The calibrated projection: every job priced as newdata prices a piloted job (fits_per_outer x mean pilot seconds x the
    calibration factor of the realized bridge_knn and knn_training runs, central pooled and upper max, plus the job
    overhead); the decision is the central simulated makespan at the family's workers plus STAGE_OVERHEAD_HOURS."""
    pilot_path = Path(pilot_path)
    pilot = json.loads(pilot_path.read_text())
    if pilot.get('protocol_hash') != config_id(protocol):
        raise ValueError('The pilot did not run with this protocol')
    calibration = calibration or CALIBRATION
    factors = {}
    for label, models in CALIBRATION_MODELS.items():
        factors.update(nd.calibration_factors(calibration[label]['run'],
                                              json.loads(Path(calibration[label]['pilot']).read_text()), models))
    names = list(protocol['datasets'])
    means = nd.pilot_means(pilot)
    registry = build_registry(protocol)
    per_outer = {model: nd.fits_per_outer(len(spec.candidates), spec.stochastic, protocol['inner_folds'])
                 for model, spec in registry.items()}
    missing = [f'{name} {model}' for name in names for model in MODEL_ORDER if (name, model) not in means]
    if missing:
        raise ValueError(f'The pilot must time every model on every dataset (missing {missing})')
    jobs = {(name, model): {kind: factors[CALIBRATION_SOURCE[model]][factor] * per_outer[model] * means[name, model]
                                  + nd.JOB_OVERHEAD_SECONDS for kind, factor in KINDS.items()}
            for name in names for model in MODEL_ORDER}
    folds = protocol['outer_folds'] * protocol['outer_repeats']
    durations = {kind: [jobs[name, model][kind] for name in names for _ in range(folds) for model in MODEL_ORDER]
                 for kind in KINDS}
    run_hours = {kind: {'serial_hours': sum(durations[kind]) / 3600,
                        'serial_over_workers_hours': sum(durations[kind]) / 3600 / WORKERS,
                        'simulated_makespan_hours': nd.makespan(durations[kind], WORKERS) / 3600} for kind in KINDS}
    total = {kind: run_hours[kind]['simulated_makespan_hours'] + STAGE_OVERHEAD_HOURS for kind in KINDS}
    harness = sum(pilot['workload_estimates'][model]['serial_panel_seconds_using_observed_max']
                  for model in MODEL_ORDER) / 3600 / WORKERS
    return _plain({
        'purpose': f'{FAMILY}_calibrated_projection', 'family': FAMILY, 'protocol_id': protocol['protocol_id'],
        'protocol_hash': config_id(protocol), 'cap_hours': CAP_HOURS, 'workers': WORKERS,
        'decision': f'calibrated central simulated makespan at {WORKERS} workers of the run jobs plus '
                    f'{STAGE_OVERHEAD_HOURS} h of stage overhead (prepare, data properties, reporting, analysis)',
        'decision_hours': total['central'], 'upper_hours': total['upper'], 'within_cap': total['central'] <= CAP_HOURS,
        'run': run_hours, 'stage_overhead_hours': STAGE_OVERHEAD_HOURS, 'harness_max_based_run_hours': harness,
        'per_dataset': {name: {'central_serial_hours': folds * sum(jobs[name, model]['central'] for model in MODEL_ORDER) / 3600,
                               'upper_serial_hours': folds * sum(jobs[name, model]['upper'] for model in MODEL_ORDER) / 3600,
                               'arrowflow_job_minutes': {kind: jobs[name, TRAINED_MODEL][kind] / 60 for kind in KINDS},
                               'central_serial_hours_by_model': {model: folds * jobs[name, model]['central'] / 3600
                                                                 for model in MODEL_ORDER}} for name in names},
        'calibration': factors, 'calibration_source': CALIBRATION_SOURCE, 'fits_per_outer': per_outer,
        'job_seconds': {f'{name}|{model}': jobs[name, model] for name in names for model in MODEL_ORDER},
        'assumptions': 'the calibration factors were measured under 16 single-thread workers of the bridge_knn and '
                       'knn_training production runs and are applied at this family\'s workers; every native model takes the '
                       'factor of the encoded-run model with the same job structure, which prices the native networks with '
                       'an encoder\'s cost included and is therefore conservative; other families running at the same time '
                       'add contention the factors do not hold, and inflate the pilot itself',
        'sources': {'pilot': {'path': str(pilot_path), 'sha256': sha256_file(pilot_path)},
                    **{label: {'run': str(entry['run']), 'pilot': str(entry['pilot']),
                               'pilot_sha256': sha256_file(entry['pilot'])} for label, entry in calibration.items()}}})


def freeze(draft_path, projection_path, stages_path, output_path=None, *, frozen_at_utc=None):
    """The frozen protocol from the committed draft, only if every dataset is pinned and the calibrated projection of that
    draft's pilot is within the cap; an existing file with different content is never replaced."""
    from .run_revision import write_json
    draft = json.loads(Path(draft_path).read_text())
    if draft.get('production_family') != FAMILY or canonical_json(draft) != canonical_json(draft_protocol()):
        raise ValueError('The draft differs from native_artificial.draft_protocol(); the stages must have used the '
                         'committed draft')
    unpinned = [entry['name'] for entry in draft['panel'] if not entry.get('pinned', True)]
    if unpinned:
        raise ValueError(f'Not frozen: {", ".join(unpinned)} not pinned')
    plan, stages = json.loads(Path(projection_path).read_text()), json.loads(Path(stages_path).read_text())
    if plan.get('protocol_hash') != config_id(draft) or plan.get('family') != FAMILY or plan.get('workers') != WORKERS:
        raise ValueError('The projection was not computed from a pilot of this draft at the family workers')
    if not plan.get('within_cap') or not 0 < plan['decision_hours'] <= CAP_HOURS:
        raise ValueError(f'Not frozen: the calibrated projection {plan["decision_hours"]:.2f} h exceeds the {CAP_HOURS} h cap '
                         f'at {WORKERS} workers')
    record = {'cap_hours': CAP_HOURS, 'workers': WORKERS, 'decision': plan['decision'],
              'decision_hours': plan['decision_hours'], 'upper_hours': plan['upper_hours'], 'run': plan['run'],
              'stage_overhead_hours': plan['stage_overhead_hours'],
              'harness_max_based_run_hours': plan['harness_max_based_run_hours'],
              'per_dataset': {name: {key: entry[key] for key in ('central_serial_hours', 'upper_serial_hours',
                                                                 'arrowflow_job_minutes')}
                              for name, entry in plan['per_dataset'].items()},
              'calibration_factors': {model: {'pooled': f['pooled'], 'max': f['max']} for model, f in plan['calibration'].items()},
              'calibration_source': plan['calibration_source'], 'assumptions': plan['assumptions'],
              'projection_sha256': sha256_file(projection_path), 'stages': stages}
    text = (f'Native-input artificial family (author correction 2026-09-15): ArrowFlow on the completed ranking with no '
            f'encoder, the four models declared here, the classical comparators reused from the encoded run; '
            f'{stages["summary"]}; projected at {WORKERS} single-thread workers as the calibrated central simulated '
            f'makespan of the run ({plan["run"]["central"]["simulated_makespan_hours"]:.2f} h) plus '
            f'{plan["stage_overhead_hours"]} h of stage overhead: {plan["decision_hours"]:.2f} h (upper '
            f'{plan["upper_hours"]:.2f} h; harness max-based run {plan["harness_max_based_run_hours"]:.2f} h); cap '
            f'{CAP_HOURS} h; frozen after the pilot')
    protocol = validate_native_protocol(_plain(dict(
        draft, frozen=True, frozen_at_utc=frozen_at_utc or datetime.now(timezone.utc).isoformat(), status=FROZEN_STATUS,
        resource_decision=text, projection=record)))
    write_json(Path(output_path or PROTOCOL_FILE), protocol)
    return protocol


