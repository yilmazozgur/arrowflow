def _validate_smoke(p):
    panel = p.get('panel')
    if (not isinstance(panel, list) or not panel or any(not isinstance(entry, dict) for entry in panel)
            or len({entry.get('name') for entry in panel}) != len(panel)
            or any(entry.get('role') not in ROLES for entry in panel) or not family_members(panel)):
        raise ValueError('A synthetic smoke panel holds uniquely named datasets with the role family or descriptive and at '
                         'least one family member')
    members = family_members(panel)
    if (p.get('registry') != SMOKE_REGISTRY or p.get('datasets') != [entry['name'] for entry in panel]
            or p.get('primary_family_size') != len(members) or p.get('secondary_family_size') != len(members)
            or p.get('multiplicity') != multiplicity(len(members)) or p.get('analysis') != analysis_declaration(panel)
            or p.get('frozen') is not True or not str(p.get('protocol_id', '')).endswith('-synthetic-smoke')
            or any(type(p.get(key)) is not int or p[key] < 2 for key in ('outer_folds', 'inner_folds'))
            or type(p.get('outer_repeats')) is not int or p['outer_repeats'] < 1):
        raise ValueError('A synthetic smoke protocol is frozen, names the smoke registry and declares its datasets, family '
                         'sizes, multiplicity and analysis from its panel')
    return p


def validate_native_protocol(p):
    """A production protocol is the draft, or the draft with exactly the freeze fields set by `freeze`; a synthetic smoke
    protocol is the draft with its synthetic panel, design and analysis."""
    if not isinstance(p, dict) or p.get('production_family') != FAMILY:
        raise ValueError(f'production_family must be {FAMILY!r}')
    draft = draft_protocol()
    smoke = p.get('purpose') == 'synthetic_smoke_only'
    ignored = SMOKE_FIELDS if smoke else FREEZE_FIELDS
    differing = sorted(key for key in set(p) | set(draft)
                       if key not in ignored and canonical_json(p.get(key)) != canonical_json(draft.get(key)))
    if differing:
        raise ValueError(f'The protocol differs from native_artificial.draft_protocol() in {", ".join(differing)}')
    if smoke:
        return _validate_smoke(p)
    if not p.get('frozen'):
        if canonical_json(p) != canonical_json(draft):
            raise ValueError('An unfrozen protocol must equal the draft')
        return p
    plan = p.get('projection') or {}
    decision = plan.get('decision_hours')
    if (p.get('status') != FROZEN_STATUS or not p.get('frozen_at_utc') or not p.get('resource_decision')
            or plan.get('cap_hours') != CAP_HOURS or plan.get('workers') != WORKERS
            or isinstance(decision, bool) or not isinstance(decision, (int, float)) or not 0 < decision <= CAP_HOURS):
        raise ValueError(f'A frozen protocol records its freeze and a calibrated projection within the {CAP_HOURS} h cap at '
                         f'{WORKERS} workers')
    if any(not entry.get('pinned', True) for entry in p['panel']):
        raise ValueError('A frozen protocol pins every dataset')
    return p


