def synthetic_dataset(entry, index):
    """Partial rankings over `items` items in three classes, in the artificial feature form (position / (m - 1), NaN for a
    deleted item): each class is a prototype order corrupted by adjacent swaps and deletions."""
    rng = np.random.RandomState(211 + index)
    V, n = int(entry['items']), int(entry['samples'])
    prototypes = [list(range(1, V + 1)), list(range(V, 0, -1)), list(range(1, V + 1, 2)) + list(range(2, V + 1, 2))]
    X = np.full((n, V), np.nan)
    y = np.tile([0, 1, 2], n // 3)
    for row, label in enumerate(y):
        order = list(prototypes[label])
        for _ in range(rng.randint(0, 3)):
            j = rng.randint(len(order) - 1)
            order[j], order[j + 1] = order[j + 1], order[j]
        for _ in range(rng.randint(0, 3)):
            if len(order) > 2:
                order.pop(rng.randint(len(order)))
        for position, item in enumerate(order):
            X[row, item - 1] = position / (len(order) - 1)
    return X, np.asarray(y)


