    if ARTIFICIAL_PROTOCOL_FILE.is_file():
        artificial = json.loads(ARTIFICIAL_PROTOCOL_FILE.read_text())
        differing = sorted(key for key in DESIGN_KEYS
                           if canonical_json(artificial.get(key)) != canonical_json(protocol[key]))
