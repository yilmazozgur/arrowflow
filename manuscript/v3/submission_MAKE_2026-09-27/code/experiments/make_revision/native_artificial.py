def draft_protocol():
    """The unfrozen stage protocol: the nested design of newdata_batch1.json (checked against the artificial protocol), the
    pinned panel, the four native models and the prespecified analysis."""
    template = json.loads(TEMPLATE.read_text())
    missing = [key for key in DESIGN_KEYS if key not in template]
    if missing:
        raise ValueError(f'newdata_batch1.json no longer declares {", ".join(missing)}')
    if [key for key, value in nd.DESIGN.items() if template[key] != value]:
        raise ValueError('newdata_batch1.json no longer holds the newdata nested design')
