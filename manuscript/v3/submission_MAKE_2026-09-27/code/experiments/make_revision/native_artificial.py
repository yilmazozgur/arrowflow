class NativeFootruleKNN(ClassifierMixin, BaseEstimator):
    """StableFootruleKNN on the completed input rankings themselves (footrule = L1 on the position vectors)."""
    def __init__(self, n_neighbors=5, weights='uniform'):
        self.n_neighbors = n_neighbors
        self.weights = weights

    def fit(self, X, y):
        start = time.perf_counter()
        orders = native_orders(X)
        self.completion_seconds_ = time.perf_counter() - start
        self.encoding_seconds_ = 0.
        self.vocabulary_size_ = int(orders.shape[1])
        self.model_ = StableFootruleKNN(n_neighbors=self.n_neighbors, weights=self.weights).fit(orders, y)
        self.classes_ = self.model_.classes_
        self.classifier_fit_seconds_ = self.model_.classifier_fit_seconds_
        self.representation_metadata_ = {'readout': 'knn_input', 'input': COMPLETION_RULE,
                                         'encoder': 'none (native ranking input)', 'vocabulary_size': self.vocabulary_size_,
                                         'representation': 'inverse positions of the completed input ranking',
                                         'completion_seconds': self.completion_seconds_}
        return self

    def predict(self, X):
        check_is_fitted(self, 'model_')
        start = time.perf_counter()
        orders = native_orders(X)
        if orders.shape[1] != self.vocabulary_size_:
            raise ValueError('Item vocabulary changed')
        self.last_completion_seconds_ = time.perf_counter() - start
        self.last_encoding_seconds_ = 0.
        return self.model_.predict(orders)


