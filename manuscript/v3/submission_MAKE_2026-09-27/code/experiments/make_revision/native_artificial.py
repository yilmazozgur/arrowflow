# ----------------------------------------------------------------------------- descriptive data properties

PROBES = {
    'missing_count': 'the number of items the row omits, and nothing else',
    'missing_items': 'the identity of the items the row omits (exactly the appended tail), and nothing else',
    'majority_class': 'nothing: the training majority class (the reference for both probes)'}
PROBE_RULE = ('per outer fold of the declared splits, predict the majority training class among the training rows sharing the '
              'probe key, falling back to the overall training majority for a key absent from the training rows; ties inside a '
              'key and in the fallback go to the lowest class label. Deterministic, no seed, no tuning, no model: a property '
              'of the data under the folds the family uses')
PROBE_STATUS = ('descriptive data-property measurement of the completion artifact, computed before any outer score of this '
                'family exists; it is never a model of the panel and never enters a family')


def probe_keys(X, probe):
    if probe == 'missing_count':
        return [int(count) for count in missing_counts(X)]
    if probe == 'missing_items':
        return list(missing_items(X))
    if probe == 'majority_class':
        return [()] * len(np.asarray(X))
    raise ValueError(f'probe must be one of {", ".join(PROBES)}')


def _majority_label(labels):
    values, counts = np.unique(np.asarray(labels), return_counts=True)
    return values[int(np.argmax(counts))]           # argmax takes the first maximum: the lowest class label


def probe_accuracies(X, y, splits, probe):
    """Per outer fold, the accuracy of the key-lookup rule of PROBE_RULE."""
    keys, y = probe_keys(X, probe), np.asarray(y)
    accuracies = []
    for split in splits:
        train, test = list(split['train']), list(split['test'])
        groups = {}
        for row in train:
            groups.setdefault(keys[row], []).append(y[row])
        table = {key: _majority_label(labels) for key, labels in groups.items()}
        fallback = _majority_label(y[train])
        predicted = np.asarray([table.get(keys[row], fallback) for row in test])
        accuracies.append(float(np.mean(predicted == y[test])))
    return accuracies


def data_properties(protocol, names=None, *, loaders=None):
    """The descriptive completion-artifact probes of every dataset, with the completion audit."""
    names = list(protocol['datasets'] if names is None else names)
    entries = panel_by_name(protocol)
    record = {'purpose': 'native_artificial_completion_artifact_and_data_properties', 'status': PROBE_STATUS,
              'probes': PROBES, 'rule': PROBE_RULE, 'completion': COMPLETION_RULE, 'artifact': COMPLETION_ARTIFACT,
              'protocol_id': protocol['protocol_id'], 'protocol_hash': config_id(protocol), 'datasets': {}}
    for name in names:
        X, y, manifest = load(name, protocol, loaders=loaders)
        splits = make_splits(y, protocol['outer_folds'], protocol['outer_repeats'], protocol['inner_folds'],
                             protocol['split_seed'])
        if config_id(splits) != entries[name]['splits_hash'] or manifest['dataset_hash'] != entries[name]['dataset_hash']:
            raise DatasetIdentityError(f'{name}: the dataset or splits hash differs from the panel pins')
        audit = check_completion(name, X)
        probes = {}
        for probe in PROBES:
            accuracies = probe_accuracies(X, y, splits, probe)
            probes[probe] = {'definition': PROBES[probe], 'mean_accuracy': float(np.mean(accuracies)),
                             'outer_fold_sd': float(np.std(accuracies, ddof=1)), 'n_folds': len(accuracies),
                             'distinct_keys': int(len(set(map(str, probe_keys(X, probe))))),
                             'fold_accuracies': accuracies}
        for probe in ('missing_count', 'missing_items'):
            probes[probe]['above_majority_points'] = round(100 * (probes[probe]['mean_accuracy']
                                                                  - probes['majority_class']['mean_accuracy']), 9)
        record['datasets'][name] = {'role': entries[name]['role'], 'completion_audit': audit, 'probes': probes}
    return _plain(record)


